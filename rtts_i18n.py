"""RTTS's own text (buttons, settings, messages) in other languages.

tr("English text") returns that text in the language picked in Settings > General > Language. The English text
itself is the key, so anything without a translation simply shows in English. Placeholders like %s and %d must
stay exactly as they are in each translation (the same ones, in the same order).
"""
import ctypes
import sys

# (code, the language's own name). The voice languages are separate (RTTS.py LANGUAGES), but the same list.
UI_LANGUAGES = [
    ("en", "English"), ("es", "Español"), ("fr", "Français"), ("pt", "Português (Brasil)"), ("de", "Deutsch"),
    ("hi", "हिन्दी"), ("ru", "Русский"), ("ar", "العربية"), ("zh", "中文 (简体)"),
]

# The bundled Space Mono only has Latin letters. These languages use a Windows font made for their script
# instead (all ship with Windows 10 and 11), at a size that keeps the letters readable.
UI_FONTS = {
    "ru": ("Consolas", 9),
    "hi": ("Nirmala UI", 10),
    "ar": ("Segoe UI", 10),
    "zh": ("Microsoft YaHei UI", 9),
}

_current = {"code": "en"}


def set_ui_language(code):
    _current["code"] = code if code in dict(UI_LANGUAGES) else "en"


def ui_language():
    return _current["code"]


def tr(text):
    """`text` in RTTS's language (or as it is, if there's no translation)."""
    return TRANSLATIONS.get(_current["code"], {}).get(text, text)


def windows_ui_language():
    """Windows' display language, if RTTS has it; otherwise English."""
    if sys.platform != "win32":
        return "en"
    try:
        primary = ctypes.windll.kernel32.GetUserDefaultUILanguage() & 0x3FF
    except Exception:
        return "en"
    return {0x09: "en", 0x0A: "es", 0x0C: "fr", 0x16: "pt", 0x07: "de", 0x39: "hi", 0x19: "ru", 0x01: "ar",
            0x04: "zh"}.get(primary, "en")


